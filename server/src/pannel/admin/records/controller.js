import PDFDocument from "pdfkit";
import "pdfkit-table";
import { attendance } from "../database/attendance.model.js";

export const downloadAttendancePdf = async (req, res) => {
  try {
    const Attendance = await attendance.find({}).sort({ Date: -1 });

    if (!Attendance.length) {
      return res
        .status(404)
        .json({ success: false, message: "No attendance record found" });
    }

    const doc = PDFDocument({
      size: "A4",
      margin: 30,
    });

    res.setHeader("Content-Type", "application/pdf");
    res.setHeader(
      "Content-Disposition",
      `attachment; filename="Attendance_Report.pdf"`,
    );

    doc.pipe(res);
    doc.fontSize(20).font("Helvetica-Bold").text("ATTENDANCE REPORT", {
      align: "center",
    });

    doc.moveDown();
    doc
      .fontSize(10)
      .font("Helvetica")
      .text(`Generated: ${new Date().toLocaleString("en-IN")}`, {
        align: "center",
      });

    doc.moveDown(2);
    const total = attendance.length;

    const present = attendance.filter(
      (item) => item.status === "Present",
    ).length;

    const absent = attendance.filter((item) => item.status === "Absent").length;

    const matched = attendance.filter(
      (item) => item.matched === "Matched",
    ).length;

    const failed = attendance.filter(
      (item) => item.matched === "Failed",
    ).length;

    doc.fontSize(12).font("Helvetica-Bold");

    doc.text(`Total Records: ${total}`);
    doc.text(`Present: ${present}`);
    doc.text(`Absent: ${absent}`);
    doc.text(`Matched: ${matched}`);
    doc.text(`Failed: ${failed}`);

    doc.moveDown(2);

    const rows = attendance.map((item) => [
      item.name || item.studentName || "Unknown",
      item.date ? new Date(item.date).toLocaleDateString("en-IN") : "-",
      item.time || "-",
      item.status || "-",
      item.matched || "-",
      `${item.confidence || 0}%`,
    ]);

    await doc.table({
      headers: ["Name", "Date", "Time", "Status", "Matched", "Confidence"],

      rows,

      options: {
        width: 535,
        padding: 5,
        prepareHeader: () => {
          doc.font("Helvetica-Bold").fontSize(8);
        },
        prepareRow: () => {
          doc.font("Helvetica").fontSize(8);
        },
      },
    });

    doc.moveDown();

    doc.fontSize(8).text("Generated by Attendance Management System", {
      align: "center",
    });

    doc.end();
  } catch (error) {
    console.error("PDF Error:", error);

    if (!res.headersSent) {
      return res.status(500).json({
        success: false,
        message: "Failed to generate PDF",
      });
    }
  }
};
